-- Registro de operações administrativas relevantes (mudança de perfil, gestão do catálogo de tipos).
-- Somente acréscimo; não altera migrations anteriores.

CREATE TABLE auditoria_administrativa (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    acao VARCHAR(60) NOT NULL,
    entidade VARCHAR(60) NOT NULL,
    entidade_id INTEGER,
    detalhes TEXT,
    data_evento TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_auditoria_admin_usuario ON auditoria_administrativa (usuario_id);
CREATE INDEX idx_auditoria_admin_data ON auditoria_administrativa (data_evento DESC, id DESC);

CREATE TRIGGER trg_auditoria_administrativa_imutavel
    BEFORE UPDATE OR DELETE ON auditoria_administrativa
    FOR EACH ROW EXECUTE FUNCTION bloquear_alteracao_registro_auditoria();
