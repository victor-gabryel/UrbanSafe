-- Mídias, histórico e moderação de ocorrências (documento "Tecnologias e Metodologia", seções 12.1.5, 12.1.6 e 12.1.8).
-- Não altera migrations anteriores. IDs e FKs seguem a convenção do projeto (INTEGER IDENTITY).

CREATE TYPE tipo_midia AS ENUM ('IMAGEM', 'VIDEO', 'AUDIO', 'DOCUMENTO');
CREATE TYPE acao_moderacao AS ENUM ('APROVAR', 'REJEITAR', 'SOLICITAR_CORRECAO', 'OCULTAR_TEMPORARIAMENTE');

-- Função usada pelos gatilhos de imutabilidade das tabelas de auditoria.
CREATE FUNCTION bloquear_alteracao_registro_auditoria() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Registros de auditoria são imutáveis (% em %).', TG_OP, TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

-- Mídias: o arquivo fica fora do banco; "url" guarda a chave interna do armazenamento (não é URL pública).
CREATE TABLE midias_ocorrencia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id INTEGER NOT NULL REFERENCES ocorrencias(id) ON DELETE RESTRICT,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    tipo tipo_midia NOT NULL,
    url TEXT NOT NULL,
    nome_arquivo VARCHAR(255),
    descricao TEXT,
    tipo_conteudo VARCHAR(100) NOT NULL,
    tamanho_bytes BIGINT NOT NULL,
    data_envio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    removida_em TIMESTAMPTZ,
    removida_por INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
    CONSTRAINT ck_midias_tamanho CHECK (tamanho_bytes >= 0),
    CONSTRAINT ck_midias_remocao CHECK (
        (removida_em IS NULL AND removida_por IS NULL) OR (removida_em IS NOT NULL AND removida_por IS NOT NULL))
);

CREATE INDEX idx_midias_ocorrencia ON midias_ocorrencia (ocorrencia_id) WHERE removida_em IS NULL;
CREATE INDEX idx_midias_usuario ON midias_ocorrencia (usuario_id);
CREATE INDEX idx_midias_removida_por ON midias_ocorrencia (removida_por) WHERE removida_por IS NOT NULL;

-- Histórico (somente acréscimo). "acao" identifica o evento; data_evento é a data oficial (não há criado_em
-- separado, evitando a duplicidade semântica citada no documento).
CREATE TABLE historico_ocorrencia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id INTEGER NOT NULL REFERENCES ocorrencias(id) ON DELETE RESTRICT,
    usuario_id INTEGER REFERENCES usuarios(id) ON DELETE RESTRICT,
    acao VARCHAR(40) NOT NULL,
    status_anterior status_ocorrencia,
    status_novo status_ocorrencia,
    descricao TEXT NOT NULL,
    data_evento TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_historico_acao CHECK (acao IN
        ('CRIACAO', 'ATUALIZACAO', 'MUDANCA_STATUS', 'MODERACAO', 'EXCLUSAO', 'MIDIA_ADICIONADA', 'MIDIA_REMOVIDA'))
);

CREATE INDEX idx_historico_ocorrencia ON historico_ocorrencia (ocorrencia_id, data_evento, id);
CREATE INDEX idx_historico_usuario ON historico_ocorrencia (usuario_id) WHERE usuario_id IS NOT NULL;

CREATE TRIGGER trg_historico_ocorrencia_imutavel
    BEFORE UPDATE OR DELETE ON historico_ocorrencia
    FOR EACH ROW EXECUTE FUNCTION bloquear_alteracao_registro_auditoria();

-- Moderação (somente acréscimo). status_anterior/status_novo foram acrescentados ao modelo do documento
-- para tornar cada decisão auditável por si só.
CREATE TABLE moderacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id INTEGER NOT NULL REFERENCES ocorrencias(id) ON DELETE RESTRICT,
    moderador_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    acao acao_moderacao NOT NULL,
    status_anterior status_ocorrencia NOT NULL,
    status_novo status_ocorrencia NOT NULL,
    justificativa TEXT,
    data_moderacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_moderacoes_justificativa CHECK (
        acao = 'APROVAR' OR (justificativa IS NOT NULL AND LENGTH(BTRIM(justificativa)) > 0))
);

CREATE INDEX idx_moderacoes_ocorrencia ON moderacoes (ocorrencia_id, data_moderacao, id);
CREATE INDEX idx_moderacoes_moderador ON moderacoes (moderador_id);

CREATE TRIGGER trg_moderacoes_imutavel
    BEFORE UPDATE OR DELETE ON moderacoes
    FOR EACH ROW EXECUTE FUNCTION bloquear_alteracao_registro_auditoria();
