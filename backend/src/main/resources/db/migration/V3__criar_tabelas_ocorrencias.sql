-- Catálogo de tipos e ocorrências (documento "Tecnologias e Metodologia", seções 12.1.3, 12.1.4 e 13).
-- Mídias, histórico, moderações e rotas ficam para migrations próprias.

CREATE TYPE status_ocorrencia AS ENUM ('PENDENTE', 'PUBLICADA', 'REJEITADA', 'OCULTA');

-- Tipos de ocorrência
CREATE TABLE tipos_ocorrencia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao TEXT,
    categoria VARCHAR(80),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    exige_revisao BOOLEAN NOT NULL DEFAULT TRUE
);

-- Ocorrências
CREATE TABLE ocorrencias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    tipo_ocorrencia_id INTEGER NOT NULL REFERENCES tipos_ocorrencia(id) ON DELETE RESTRICT,
    titulo VARCHAR(150) NOT NULL,
    descricao TEXT NOT NULL,
    latitude NUMERIC(10,7) NOT NULL,
    longitude NUMERIC(10,7) NOT NULL,
    endereco TEXT,
    data_ocorrencia TIMESTAMPTZ,
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status status_ocorrencia NOT NULL DEFAULT 'PENDENTE',
    relevancia VARCHAR(10) NOT NULL DEFAULT 'MEDIA',
    anonimato BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_ocorrencias_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_ocorrencias_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_ocorrencias_relevancia CHECK (relevancia IN ('BAIXA', 'MEDIA', 'ALTA'))
);

CREATE INDEX idx_ocorrencias_usuario ON ocorrencias (usuario_id);
CREATE INDEX idx_ocorrencias_tipo ON ocorrencias (tipo_ocorrencia_id);
CREATE INDEX idx_ocorrencias_status ON ocorrencias (status);
CREATE INDEX idx_ocorrencias_data_ocorrencia ON ocorrencias (data_ocorrencia);
CREATE INDEX idx_ocorrencias_data_cadastro ON ocorrencias (data_cadastro);
-- Filtro por área retangular (mapa). Consultas espaciais reais exigiriam PostGIS, ainda não habilitado.
CREATE INDEX idx_ocorrencias_coordenadas ON ocorrencias (latitude, longitude);

