-- Consultas de rota (documento "Tecnologias e Metodologia", seções 12.1.7 e 15.2.7).
-- Migração incremental: não altera V1-V6 e preserva os dados.
--
-- Regras de privacidade (seção 12.1.7 e 17): somente consultas de usuário AUTENTICADO são gravadas;
-- consultas anônimas são calculadas e devolvidas, mas não persistidas. A coluna usuario_id aceita NULL
-- conforme o modelo (ON DELETE SET NULL: a rota sobrevive sem vínculo se a conta for removida).
-- Unidades: distancia em METROS; tempo_estimado em SEGUNDOS; indice_exposicao na escala 0 a 100.

CREATE TABLE rotas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    origem VARCHAR(255),
    destino VARCHAR(255),
    origem_latitude NUMERIC(10,7) NOT NULL,
    origem_longitude NUMERIC(10,7) NOT NULL,
    destino_latitude NUMERIC(10,7) NOT NULL,
    destino_longitude NUMERIC(10,7) NOT NULL,
    distancia NUMERIC(10,2) NOT NULL,
    tempo_estimado INTEGER NOT NULL,
    indice_exposicao NUMERIC(5,2),
    data_calculo TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_rotas_origem_latitude CHECK (origem_latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_rotas_origem_longitude CHECK (origem_longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_rotas_destino_latitude CHECK (destino_latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_rotas_destino_longitude CHECK (destino_longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_rotas_distancia CHECK (distancia >= 0),
    CONSTRAINT ck_rotas_tempo CHECK (tempo_estimado >= 0),
    CONSTRAINT ck_rotas_indice CHECK (indice_exposicao IS NULL OR indice_exposicao BETWEEN 0 AND 100)
);

CREATE INDEX idx_rotas_usuario_data ON rotas (usuario_id, data_calculo DESC, id DESC)
    WHERE usuario_id IS NOT NULL;
